"""
Gzip everything in esp32/web/ into src/web_assets.h, so the firmware serves
the app straight from flash -- one upload, no filesystem image.

Runs automatically before every PlatformIO build (extra_scripts in
platformio.ini). Can also be run by hand:  python esp32/tools/embed_web.py
"""
import gzip
import os

MIME = {
    ".html": "text/html; charset=utf-8",
    ".js": "application/javascript",
    ".css": "text/css",
    ".json": "application/json",
    ".svg": "image/svg+xml",
    ".png": "image/png",
    ".ico": "image/x-icon",
    ".webmanifest": "application/manifest+json",
}


def build(root):
    web = os.path.join(root, "web")
    out = os.path.join(root, "src", "web_assets.h")
    files = sorted(f for f in os.listdir(web) if os.path.splitext(f)[1] in MIME)
    lines = ["// Generated by tools/embed_web.py from esp32/web/ -- do not edit.",
             "#pragma once", "#include <cstddef>", "#include <cstdint>", "",
             "struct WebAsset { const char* path; const char* mime; const uint8_t* data; size_t len; };",
             ""]
    total = 0
    for i, name in enumerate(files):
        with open(os.path.join(web, name), "rb") as fh:
            raw = fh.read()
        # mtime=0 keeps the output byte-identical between builds.
        gz = gzip.compress(raw, compresslevel=9, mtime=0)
        total += len(gz)
        body = ",".join(str(b) for b in gz)
        lines.append(f"// {name}: {len(raw)} bytes, {len(gz)} gzipped")
        lines.append(f"static const uint8_t WEB_ASSET_{i}[] = {{{body}}};")
    lines.append("")
    lines.append("static const WebAsset WEB_ASSETS[] = {")
    for i, name in enumerate(files):
        mime = MIME[os.path.splitext(name)[1]]
        lines.append(f'    {{"/{name}", "{mime}", WEB_ASSET_{i}, sizeof(WEB_ASSET_{i})}},')
    lines.append("};")
    lines.append(f"static const size_t WEB_ASSET_COUNT = {len(files)};")
    text = "\n".join(lines) + "\n"
    old = open(out).read() if os.path.exists(out) else None
    if text != old:
        with open(out, "w") as fh:
            fh.write(text)
    print(f"embed_web: {len(files)} files, {total} bytes gzipped")


try:
    Import("env")  # noqa: F821 -- PlatformIO
    build(env.subst("$PROJECT_DIR"))  # noqa: F821
except NameError:
    build(os.path.abspath(os.path.join(os.path.dirname(__file__), "..")))
